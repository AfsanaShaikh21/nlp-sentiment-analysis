# ==========================================
# LOAD MODEL
# ==========================================

@st.cache_resource
def load_model():

    tokenizer = AutoTokenizer.from_pretrained(MODEL_REPO)

    model = AutoModelForSequenceClassification.from_pretrained(
        MODEL_REPO
    )

    model.eval()

    return tokenizer, model


try:

    with st.spinner("Loading AI model..."):

        tokenizer, model = load_model()

    st.success("🟢 AI Model Ready")

    # ======================================
    # REVIEW INPUT
    # ======================================

    st.markdown('<div class="section-card">',
                unsafe_allow_html=True)

    st.markdown("### ✍️ Enter Your Review")

    st.write(
        "Write a product, service, or customer review "
        "to analyze its sentiment."
    )

    review = st.text_area(
        "Your Review",
        placeholder="Example: The product quality is amazing. "
                    "I really enjoyed using it!",
        height=160,
        label_visibility="collapsed"
    )

    st.caption(f"Characters entered: {len(review)}")

    predict_button = st.button(
        "✨ Analyze Sentiment",
        use_container_width=True
    )

    st.markdown('</div>', unsafe_allow_html=True)


    # ======================================
    # PREDICTION
    # ======================================

    if predict_button:

        if review.strip():

            inputs = tokenizer(
                review,
                return_tensors="pt",
                truncation=True,
                max_length=256
            )

            with torch.no_grad():

                outputs = model(**inputs)

                probabilities = torch.softmax(
                    outputs.logits,
                    dim=1
                )

            predicted_id = torch.argmax(
                probabilities,
                dim=1
            ).item()

            label_map = model.config.id2label

            sentiment = label_map.get(
                predicted_id,
                label_map.get(
                    str(predicted_id),
                    str(predicted_id)
                )
            )

            confidence = (
                probabilities[0][predicted_id].item() * 100
            )

            # ==================================
            # RESULT DISPLAY
            # ==================================

            sentiment_lower = sentiment.lower()

            if "positive" in sentiment_lower:
                emoji = "😊"
                color = "#22c55e"

            elif "negative" in sentiment_lower:
                emoji = "😞"
                color = "#ef4444"

            else:
                emoji = "😐"
                color = "#3b82f6"

            st.markdown("## 📊 Analysis Result")

            st.markdown(
                f"""
                <div class="result-card">
                    <div class="result-label">
                        PREDICTED SENTIMENT
                    </div>
                    <div class="result-value">
                        {emoji} {sentiment}
                    </div>
                </div>
                """,
                unsafe_allow_html=True
            )

            st.write("### 🎯 Prediction Confidence")

            st.progress(int(confidence))

            st.markdown(
                f"**Confidence Score: {confidence:.2f}%**"
            )

            # Individual class probabilities

            st.write("### 📈 Sentiment Probability Distribution")

            for class_id, probability in enumerate(
                probabilities[0].tolist()
            ):

                label = label_map.get(
                    class_id,
                    label_map.get(str(class_id), str(class_id))
                )

                st.write(f"**{label}**")

                st.progress(probability)

                st.caption(f"{probability * 100:.2f}%")

        else:

            st.warning("⚠️ Please enter a review first.")


except Exception as e:

    st.error(f"Error loading or predicting: {e}")



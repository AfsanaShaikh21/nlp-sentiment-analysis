# 7. BULK PREDICTION
# =====================================================

def predict_bulk(reviews, tokenizer, model):

    results = []

    batch_size = 16

    for start in range(0, len(reviews), batch_size):

        batch = reviews[start:start + batch_size]

        inputs = tokenizer(
            batch,
            padding=True,
            truncation=True,
            max_length=256,
            return_tensors="pt"
        )

        with torch.inference_mode():

            outputs = model(**inputs)

            probabilities = torch.softmax(
                outputs.logits,
                dim=1
            )

        predicted_ids = probabilities.argmax(dim=1)

        for i, predicted_id in enumerate(predicted_ids):

            class_id = predicted_id.item()

            original_label = get_label(model, class_id)

            sentiment = normalize_sentiment(original_label)

            confidence = (
                probabilities[i, class_id].item() * 100
            )

            results.append({

                "Review": batch[i],

                "Sentiment": sentiment,

                "Model Label": original_label,

                "Confidence": round(confidence, 2)

            })

    return pd.DataFrame(results)



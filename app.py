def predict_single(review, tokenizer, model):

    inputs = tokenizer(
        review,
        return_tensors="pt",
        truncation=True,
        max_length=256
    )

    with torch.inference_mode():

        outputs = model(**inputs)

        probabilities = torch.softmax(
            outputs.logits,
            dim=1
        )[0]

    predicted_id = probabilities.argmax().item()

    original_label = get_label(model, predicted_id)

    sentiment = normalize_sentiment(original_label)

    confidence = probabilities[predicted_id].item() * 100

    probability_dict = {}

    for i, probability in enumerate(probabilities):

        label = get_label(model, i)

        probability_dict[label] = round(
            probability.item() * 100, 2
        )

    return sentiment, original_label, confidence, probability_dict



import streamlit as st
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification

# Hugging Face model repository
MODEL_REPO = "Afsana1753/nlp-sentiment-analysis-destibert"

# Page configuration
st.set_page_config(
    page_title="NLP Sentiment Analysis",
    page_icon="💬",
    layout="centered"
)

st.title("💬 NLP Sentiment Analysis")
st.write("Enter a review to predict its sentiment.")

# Load model and tokenizer
@st.cache_resource
def load_model():
    tokenizer = AutoTokenizer.from_pretrained(MODEL_REPO)
    model = AutoModelForSequenceClassification.from_pretrained(MODEL_REPO)
    model.eval()
    return tokenizer, model

try:
    tokenizer, model = load_model()
    st.success("DistilBERT model loaded successfully!")

    # User input
    review = st.text_area(
        "Enter your review:",
        placeholder="Write your product or service review here..."
    )

    if st.button("Predict Sentiment"):
        if review.strip():

            # Tokenize input
            inputs = tokenizer(
                review,
                return_tensors="pt",
                truncation=True,
                max_length=256
            )

            # Predict
            with torch.no_grad():
                outputs = model(**inputs)
                probabilities = torch.softmax(
                    outputs.logits,
                    dim=1
                )

            predicted_id = torch.argmax(probabilities, dim=1).item()

            # Get predicted label
            label_map = model.config.id2label
            sentiment = label_map.get(
                predicted_id,
                label_map.get(str(predicted_id), str(predicted_id))
            )

            confidence = probabilities[0][predicted_id].item() * 100

            st.subheader("Prediction Result")
            st.write(f"**Sentiment:** {sentiment}")
            st.write(f"**Confidence:** {confidence:.2f}%")

        else:
            st.warning("Please enter a review first.")

except Exception as e:
    st.error(f"Error loading or predicting: {e}")